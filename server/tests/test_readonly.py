@pytest.mark.parametrize("command", READ_ONLY)
def test_read_only_commands_pass(command):
    v = check_command(command)
    assert v, f"{command!r} was refused: {v.reason}"


@pytest.mark.parametrize("command", REFUSED)
def test_changing_commands_are_refused(command):
    v = check_command(command)
    assert not v, f"{command!r} was allowed"
    assert v.reason
